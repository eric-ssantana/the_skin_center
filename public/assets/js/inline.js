  window.updateKollektivaLanguage = function(lang) {
    lang = lang || (typeof currentLang !== 'undefined' ? currentLang : 'en');
    var list = window.kollektivaSlides[lang] || window.kollektivaSlides['en'];
    var slide = list[window.kollektivaActiveIdx || 0];
    if (!slide) return;
    var quoteEl = document.getElementById('kol-quote');
    var nameEl = document.getElementById('kol-name');
    var locEl = document.getElementById('kol-location');
    if (quoteEl) {
      quoteEl.classList.remove('kol-fadein');
      void quoteEl.offsetWidth;
      quoteEl.textContent = slide.quote;
      quoteEl.classList.add('kol-fadein');
    }
    if (nameEl) {
      nameEl.classList.remove('kol-fadein');
      void nameEl.offsetWidth;
      nameEl.textContent = slide.name;
      nameEl.classList.add('kol-fadein');
    }
    if (locEl) locEl.textContent = slide.location;
  };

